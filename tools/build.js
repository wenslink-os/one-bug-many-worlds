'use strict';
// Runs every program that has a toolchain on this machine, keeps recorded outputs
// for the rest, and writes site/data.js for the web page.
const fs = require('node:fs');
const path = require('node:path');
const { LANGS, toolVersion, runProgram } = require('./langs');

const ROOT = path.join(__dirname, '..');
const BUGS_DIR = path.join(ROOT, 'bugs');
const REC_DIR = path.join(ROOT, 'recorded');
const VERSIONS_FILE = path.join(REC_DIR, 'versions.json');

function parseChecks(stdout) {
  const out = {};
  for (const line of stdout.split('\n')) {
    if (!line.startsWith('CHECK ')) continue;
    const parts = line.slice(6).trimEnd().split('|');
    if (parts.length !== 3) continue;
    out[parts[0]] = { broken: parts[1], fixed: parts[2] };
  }
  return out;
}

function verdict(broken, correct) {
  if (broken === correct) return 'safe';
  if (broken.startsWith('ERROR ')) return 'raises';
  return 'silent';
}

function readJson(file, fallback) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) { return fallback; }
}

function collect(opts) {
  const write = !!(opts && opts.write);
  const versions = readJson(VERSIONS_FILE, {});
  const available = {};
  for (const lang of Object.keys(LANGS)) {
    const v = toolVersion(lang);
    available[lang] = v !== null;
    if (v !== null && write) versions[lang] = v;
  }
  const stale = [];
  const bugs = [];
  const dirs = fs.readdirSync(BUGS_DIR, { withFileTypes: true }).filter((d) => d.isDirectory());
  const metas = dirs.map((d) => ({ dir: d.name, meta: readJson(path.join(BUGS_DIR, d.name, 'meta.json'), null) }));
  metas.sort((a, b) => a.meta.order - b.meta.order);

  for (const { dir, meta } of metas) {
    const worlds = {};
    for (const lang of Object.keys(LANGS)) {
      const file = path.join(BUGS_DIR, dir, LANGS[lang].file);
      if (!fs.existsSync(file)) continue;
      const code = fs.readFileSync(file, 'utf8');
      const recFile = path.join(REC_DIR, meta.id, lang + '.txt');
      let output = null;
      let source = 'unrecorded';
      if (available[lang]) {
        const r = runProgram(lang, file);
        if (r.error || r.status !== 0) {
          throw new Error(meta.id + '/' + lang + ' failed: ' + (r.error ? r.error.message : r.stderr));
        }
        output = r.stdout;
        source = 'live-run';
        if (fs.existsSync(recFile) && fs.readFileSync(recFile, 'utf8') !== output) stale.push(meta.id + '/' + lang);
        if (!fs.existsSync(recFile)) stale.push(meta.id + '/' + lang);
        if (write) {
          fs.mkdirSync(path.dirname(recFile), { recursive: true });
          fs.writeFileSync(recFile, output);
        }
      } else if (fs.existsSync(recFile)) {
        output = fs.readFileSync(recFile, 'utf8');
        source = 'recorded';
      }
      let checks = null;
      if (output !== null) {
        checks = parseChecks(output);
        for (const c of meta.checks) {
          if (checks[c.id]) checks[c.id].verdict = verdict(checks[c.id].broken, c.correct);
        }
      }
      worlds[lang] = { code, source, output, checks, why: (meta.worlds && meta.worlds[lang]) || '' };
    }
    bugs.push({
      id: meta.id, title: meta.title, hook: meta.hook, concept: meta.concept, fix: meta.fix,
      checks: meta.checks, regression: meta.regression, worlds
    });
  }
  if (write) {
    fs.mkdirSync(REC_DIR, { recursive: true });
    fs.writeFileSync(VERSIONS_FILE, JSON.stringify(versions, null, 2) + '\n');
  }
  const languages = {};
  for (const lang of Object.keys(LANGS)) {
    languages[lang] = { label: LANGS[lang].label, comment: LANGS[lang].comment, version: versions[lang] || null };
  }
  return { data: { languages, bugs }, stale, available };
}

function render(data) {
  return '// Generated by tools/build.js. Do not edit by hand.\nwindow.OBMW_DATA = ' + JSON.stringify(data, null, 1) + ';\n';
}

if (require.main === module) {
  const { data, stale, available } = collect({ write: true });
  fs.writeFileSync(path.join(ROOT, 'site', 'data.js'), render(data));
  const ran = Object.keys(available).filter((k) => available[k]).join(', ');
  console.log('toolchains found: ' + (ran || 'none'));
  console.log('bugs: ' + data.bugs.length + ', recorded files refreshed: ' + stale.length);
  console.log('wrote site/data.js');
}

module.exports = { collect, render, parseChecks, verdict, ROOT, BUGS_DIR };
